#!/usr/bin/env python3
"""dump_track_dls.py — extract the 18 distinct course track index templates (segment 8,
course_track_gfx/D_8014*) from fzerox.o2r and write the two committed tables the native track
path is built on:

  port/3ds/gfx/gdx3ds_track_templates_raw.inc     the raw 8-byte GBI commands (host word order,
                                                  exactly the bytes port/gen/AssetBindings.c's
                                                  u8 D_8014xxx[] arrays hold on the device)
  port/3ds/gfx/gdx3ds_track_templates_golden.inc  the decoded golden table (tri indices +
                                                  mid-template SETCOMBINE events)

The device decodes the SAME raw arrays with gdx3ds_track_templates.c and refuses to arm if the
result differs from the golden; port/tests/track_template_tests.c runs that decoder over the
raw blobs on the host. Usage:

  python3 tools/dev/dump_track_dls.py [--o2r PATH]   (default: the Azahar virtual SD copy)

Never commits ROM data: the templates are 9-11 GBI words each (index lists), not assets.
"""
import argparse, os, struct, sys, zipfile

OTR_DL_DATA_OFFSET = 88  # 64-byte OTR header + 3 words of DisplayList resource header

# Order == GDXTRK_TEMPLATE_* indices in gdx3ds_track_templates.h. Keep stable.
TEMPLATES = [
    'D_80140F0', 'D_8014138', 'D_8014180', 'D_80141C8', 'D_8014210', 'D_8014268',
    'D_80142C0', 'D_8014308', 'D_8014350', 'D_8014398', 'D_80143E0', 'D_8014430',
    'D_8014480', 'D_80144D0', 'D_8014520', 'D_8014580', 'D_80145E0', 'D_8014640',
]

def decode(words):
    """Same contract as gdxtrk_decode_template(): tris + combine events; None if unsupported."""
    tris, events = [], []
    for w0, w1 in words:
        op = w0 >> 24
        if op == 0x06:  # G_TRI2
            tris.append((((w0 >> 16) & 0xFF) // 2, ((w0 >> 8) & 0xFF) // 2, (w0 & 0xFF) // 2))
            tris.append((((w1 >> 16) & 0xFF) // 2, ((w1 >> 8) & 0xFF) // 2, (w1 & 0xFF) // 2))
        elif op == 0x05:  # G_TRI1
            tris.append((((w0 >> 16) & 0xFF) // 2, ((w0 >> 8) & 0xFF) // 2, (w0 & 0xFF) // 2))
        elif op == 0xE7:  # G_RDPPIPESYNC: no interpreter state
            pass
        elif op == 0xFC:  # G_SETCOMBINE
            events.append((len(tris), w0, w1))
        elif op == 0xDF:  # G_ENDDL
            break
        else:
            return None
    return tris, events

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--o2r', default=os.path.expanduser(
        '~/Library/Application Support/Azahar/sdmc/3ds/gdiffuser/fzerox.o2r'))
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', '..', 'port', '3ds', 'gfx'))
    a = ap.parse_args()
    z = zipfile.ZipFile(a.o2r)
    raw_lines = ['/* AUTO-GENERATED by tools/dev/dump_track_dls.py — do not edit. Raw 8-byte GBI words of',
                 ' * the 18 course track index templates (course_track_gfx/D_8014*), host (little-endian)',
                 ' * word order as stored in fzerox.o2r and bound into port/gen/AssetBindings.c. */']
    gold_lines = ['/* AUTO-GENERATED by tools/dev/dump_track_dls.py — do not edit. Decoded golden table;',
                  ' * see gdx3ds_track_templates.h for the struct. */']
    max_bytes = 0
    for i, name in enumerate(TEMPLATES):
        data = z.read('course_track_gfx/' + name)[OTR_DL_DATA_OFFSET:]
        words = [struct.unpack('<II', data[k:k + 8]) for k in range(0, len(data), 8)]
        dec = decode(words)
        if dec is None:
            sys.exit('unsupported opcode in ' + name)
        tris, events = dec
        assert words[-1][0] >> 24 == 0xDF, name + ' does not end in G_ENDDL'
        max_bytes = max(max_bytes, len(data))
        raw_lines.append('static const unsigned char kGdxTrkRaw_%s[%d] = {' % (name, len(data)))
        for k in range(0, len(data), 16):
            raw_lines.append('    ' + ', '.join('0x%02X' % b for b in data[k:k + 16]) + ',')
        raw_lines.append('};')
        idx = ', '.join('%d,%d,%d' % t for t in tris)
        ev = ', '.join('{ %d, 0x%08XU, 0x%08XU }' % e for e in events) or '{ 0, 0, 0 }'
        maxslot = max(max(t) for t in tris)
        gold_lines.append('    /* %2d %s */ { %d, %d, %d, { %s }, { %s } },' %
                          (i, name, len(tris), len(events), maxslot, idx, ev))
        print('%2d %-10s cmds=%2d tris=%2d events=%d maxslot=%2d' % (i, name, len(words), len(tris), len(events), maxslot))
    raw_lines.append('#define GDXTRK_RAW_MAX_BYTES %d' % max_bytes)
    raw_lines.append('static const struct { const char* name; const unsigned char* raw; unsigned len; } kGdxTrkRawTable[%d] = {' % len(TEMPLATES))
    for name in TEMPLATES:
        raw_lines.append('    { "%s", kGdxTrkRaw_%s, sizeof(kGdxTrkRaw_%s) },' % (name, name, name))
    raw_lines.append('};')
    with open(os.path.join(a.out, 'gdx3ds_track_templates_raw.inc'), 'w') as f:
        f.write('\n'.join(raw_lines) + '\n')
    with open(os.path.join(a.out, 'gdx3ds_track_templates_golden.inc'), 'w') as f:
        f.write('\n'.join(gold_lines) + '\n')

if __name__ == '__main__':
    main()
