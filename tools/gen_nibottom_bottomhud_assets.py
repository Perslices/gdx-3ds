#!/usr/bin/env python3
"""tools/gen_nibottom_bottomhud_assets.py -- bake the DASH's static widgets into a C header.

COLD TOOL. Desktop-only, not part of the 3DS build (no CMake step runs this; its OUTPUT is
committed, exactly like the decomp's own yaml+baserom-derived texture arrays are checked-in
generated data, not regenerated by every build). Consumer: port/3ds/gdx3ds_bottomhud.c.

INPUT: manifest.json, tools/nibottom_template_import.py's own output format -- per widget,
x/y/w/h placement (from the Photoshop layout, nibottom-plan.md's layout.json) and raw
big-endian 16-bit pixel words (RGB565 for the opaque background, RGBA5551 r5g5b5a1 for every
other widget, which may carry transparent pixels: the DASH is drawn background-first, then
each widget composited over it, skipping alpha=0 texels -- the exact RGBA5551 a=LSB convention
port/3ds/gdx3ds_racemap.c's kMarkerRgba5551 already uses). This is this track's real answer to
the brief's "bake the static art at build time from the o2r textures" once the user's edited
template exists: the o2r extraction already happened upstream, inside
tools/nibottom_template_import.py's own pipeline (gen_nibottom_template.py sourced the layers
from the real game textures per layout.json's `source` lists); this script's job is only the
LAST mile -- raw pixel words -> a const C array -- so re-running the whole o2r extraction here
would just redo work the template tooling already did and committed to manifest.json.

EXCLUDED: the "map_box" widget. layout.json's own note on it: "stylised stand-in shown here;
SPLIT mode replaces this box with a same-coordinates placeholder at runtime" -- the real map
box is the LIVE per-race 64x64 CI8 minimap (gdx_racemap_bitmap/gdx_racemap_snapshot), drawn by
gdx3ds_bottomhud.c itself at the same 64,24,192,192 box gdx3ds_racemap.c's own MAP tab already
uses. Baking the preview PNG's pixels would just be a second, dead copy of a box nothing reads.

Usage:
    python3 tools/gen_nibottom_bottomhud_assets.py [--manifest FILE] [--out FILE]
"""
import argparse
import base64
import json
import struct
from pathlib import Path

DEFAULT_MANIFEST = (
    Path.home() / "Desktop" / "g-diffuser-builds" / "fzerox-raw-assets" / "template" /
    "import-output" / "manifest.json"
)
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "port" / "3ds" / "gdx3ds_bottomhud_assets.h"

# layout.json's own widget, not baked here -- see the module docstring.
SKIP_WIDGETS = {"map_box"}


def c_array_name(widget_id: str) -> str:
    return "kDashAsset_" + widget_id


CANVAS_W = 320
CANVAS_H = 240


def emit_widget(out, w: dict) -> None:
    raw = base64.b64decode(w["raw_base64"])
    canvas_words = CANVAS_W * CANVAS_H
    if len(raw) != canvas_words * 2:
        raise SystemExit(f"{w['id']}: raw_base64 is {len(raw)} bytes, expected the full "
                          f"{CANVAS_W}x{CANVAS_H} canvas ({canvas_words * 2})")
    canvas = struct.unpack(f">{canvas_words}H", raw)  # big-endian words, full-canvas per layer
    # Each exported layer is the FULL canvas with everything outside the widget's own x/y/w/h
    # transparent (alpha=0) -- verified against this export: zero opaque pixels fall outside the
    # bbox for every widget. Cropping to just the bbox here, once, at generation time, is a ~10x
    # size win over baking all ten full-canvas layers (and the C compositor below never has to
    # know the canvas was ever bigger than the widget it draws).
    x0, y0, ww, hh = w["x"], w["y"], w["w"], w["h"]
    values = []
    for row in range(hh):
        src = (y0 + row) * CANVAS_W + x0
        values.extend(canvas[src:src + ww])
    count = ww * hh
    name = c_array_name(w["id"])
    out.write(f"/* {w['id']}: {w['w']}x{w['h']} {w['format']} — sha256 {w['sha256'][:16]}... */\n")
    out.write(f"static const unsigned short {name}[{count}] = {{\n")
    for i in range(0, count, 12):
        row = values[i:i + 12]
        out.write("    " + ",".join(str(v) for v in row) + ",\n")
    out.write("};\n\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()

    manifest = json.loads(Path(args.manifest).read_text())
    widgets = [w for w in manifest["widgets"] if w["id"] not in SKIP_WIDGETS]

    out_path = Path(args.out)
    with out_path.open("w") as out:
        out.write(
            "/* GENERATED by tools/gen_nibottom_bottomhud_assets.py from\n"
            f" * {args.manifest}\n"
            " * (tools/nibottom_template_import.py's own output -- the user's Photoshop edit of\n"
            " * the DASH mockup, already quantised to the real RGB565/RGBA5551 framebuffer\n"
            " * formats). DO NOT HAND-EDIT -- re-run the generator after a new template export.\n"
            " * Consumer: port/3ds/gdx3ds_bottomhud.c. Contract: gdx3ds_bottomhud.h.\n"
            " *\n"
            " * Every array below is RGBA5551 r5g5b5a1 (a = LSB, alpha=0 is transparent and must\n"
            " * be skipped at blit time) EXCEPT kDashAsset_background, which is opaque RGB565\n"
            " * (the bottom layer; nothing shows through it). Both are big-endian-decoded already\n"
            " * -- host order, ready to feed straight to the same Rgba5551To565-style conversion\n"
            " * gdx3ds_racemap.c's marker palette uses, or (background) blitted directly. */\n"
            "#ifndef GDX3DS_BOTTOMHUD_ASSETS_H\n"
            "#define GDX3DS_BOTTOMHUD_ASSETS_H\n\n"
        )
        layout = {}
        for w in widgets:
            emit_widget(out, w)
            layout[w["id"]] = (w["x"], w["y"], w["w"], w["h"])
        out.write("/* id -> {array, x, y, w, h, hasAlpha} for a generic compositor loop. */\n")
        out.write("typedef struct DashAssetWidget {\n")
        out.write("    const char* id;\n")
        out.write("    const unsigned short* pixels;\n")
        out.write("    int x, y, w, h;\n")
        out.write("    int hasAlpha; /* 0 for the opaque RGB565 background, 1 for RGBA5551 */\n")
        out.write("} DashAssetWidget;\n\n")
        out.write("static const DashAssetWidget kDashAssetWidgets[] = {\n")
        for w in widgets:
            if w["id"] == "background":
                continue
            x, y, ww, hh = layout[w["id"]]
            out.write(f'    {{ "{w["id"]}", {c_array_name(w["id"])}, {x}, {y}, {ww}, {hh}, 1 }},\n')
        out.write("};\n")
        out.write("#define DASH_ASSET_WIDGET_COUNT "
                   "((int)(sizeof(kDashAssetWidgets)/sizeof(kDashAssetWidgets[0])))\n\n")
        out.write("#endif /* GDX3DS_BOTTOMHUD_ASSETS_H */\n")

    total_bytes = sum(w["w"] * w["h"] * 2 for w in widgets)
    print(f"wrote {out_path} ({len(widgets)} widgets, {total_bytes} bytes of pixel data)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
