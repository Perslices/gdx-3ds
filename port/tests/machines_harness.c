enum { K_STOCK, K_FRONT, K_REAR, K_WING, K_TEX };
typedef struct {
    const char* name;
    int kind;
    void* fn;
} FuncEntry;
#define STOCK(n) Gfx* n(Gfx*);
#define FRONT(n) Gfx* n(Gfx*, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32);
#define REAR(n) Gfx* n(Gfx*, s32, s32, s32, s32, s32, s32);
#define WING(n) Gfx* n(Gfx*, s32, s32, s32, s32, s32, s32);
