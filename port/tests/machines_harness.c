/*
 * machines_harness.c -- host differential harness for the native machine-mesh baker
 * (docs/research/native/07-machines-plan.md section 4, tests A and B).
 *
 * Links the REAL decomp emitters (decomp/src/overlays/ovl_i9/machine_draw.c, compiled with
 * the game's defines) and the generated host arrays (port/gen/AssetBindings.c) filled from
 * fzerox.o2r through a miniz implementation of GDiffuser_LoadAssetBytes, runs every
 * Machine_Draw* body emitter into a Gfx[128] buffer exactly as racer.c func_8008D3C4 does,
 * and walks the result with the device walker (port/3ds/gfx/gdx3ds_mesh_walk.c).
 *
 * Outputs (in argv[2]):
 *   lists.bin   raw host-built Gfx streams per function (for tools/native/gfx_decode.py)
 *   syms.txt    vertex-array base addresses -> o2r key (shared naming for both decoders)
 *   walk.txt    canonical per-triangle state from the walker (test A, diffed vs Python)
 *   inherit.txt colour attribution + INHERIT table (test B, diffed vs the golden file)
 *
 * Driven by tools/native/machines_harness.sh; returns 0 iff every self-check passes.
 */
