/* ---- o2r reader ----------------------------------------------------------------------- */
static mz_zip_archive sZip;
static int sZipOpen = 0;
static unsigned sVtxLoaded = 0, sVtxMissing = 0, sVtxBad = 0;

static int IsMachineVtxKey(const char* key) {
    return strncmp(key, "machine_custom_gfx/", 19) == 0 || strncmp(key, "machine_global_gfx/", 19) == 0;
}

/* GDiffuser_LoadAllAssets only fills the common assets through this; the machine VTX
 * symbols live in asset SEGMENTS (segment 3 machine_custom_gfx, 7 machine_global_gfx) that
 * the device loads as one image (bridge EnsureAssetSegmentImage + AssetBindings.c
 * gdx_fixup_asset_segment_image kind 3 = Vtx-aware byteswap). The harness fills each
 * referenced symbol lazily from its per-symbol o2r entry instead (Resolve below): 64-byte
 * OTR header, u32 count, count x 16-byte host-endian Vtx -- what LUS VertexFactory reads. */
int GDiffuser_LoadAssetBytes(const char* key, void* out, size_t outSize, size_t* copiedSize) {
    (void)key;
    (void)out;
    (void)outSize;
    (void)copiedSize;
    return 0;
}

static int LoadVtxSymbol(const char* key, unsigned char* base) {
    size_t sz = 0;
    void* data;
    uint32_t count;
    if (!sZipOpen) {
        return 0;
    }
    data = mz_zip_reader_extract_file_to_heap(&sZip, key, &sz, 0);
    if (data == NULL) {
        sVtxMissing++;
        return 0;
    }
    if (sz < 68) {
        sVtxBad++;
        mz_free(data);
        return 0;
    }
    memcpy(&count, (unsigned char*)data + 64, 4);
    if ((size_t)count * 16u + 68u > sz || count == 0 || count > 4096) {
        sVtxBad++;
        mz_free(data);
        return 0;
    }
    memcpy(base, (unsigned char*)data + 68, (size_t)count * 16u);
    mz_free(data);
    sVtxLoaded++;
    return 1;
}

/* ---- function table (generated by machines_harness.sh from machine_draw.c) ---------- */
typedef Gfx* (*StockFn)(Gfx*);
typedef Gfx* (*FrontFn)(Gfx*, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32, s32);
